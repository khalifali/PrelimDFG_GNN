#Limiting number Sn used by Wang et al., for higher particle numbers this might have to be decreased?
SN = 256

#create grid divisions according to Fig.2
GRID_DIVISIONS = tuple(
    2 ** exponent
    for exponent in range(1, int(np.log2(SN)) + 1)
)

#this loads the file as csv into np array and returns centers and radii
def load_xyzr_file(filepath):
    data = np.loadtxt(filepath, delimiter=",")

    if data.shape[1] < 4:
        raise ValueError("File must contain x, y, z, r!")

    positions = np.asarray(data[:, :3], dtype=float)
    radii = np.asarray(data[:, 3], dtype=float)
    
    return positions, radii


