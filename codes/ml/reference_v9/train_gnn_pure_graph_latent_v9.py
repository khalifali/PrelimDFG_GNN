def rotate_positions(data):
    """Apply a random rigid rotation without changing distances or contacts."""
    matrix = torch.randn(3, 3, device=data.pos.device)
    q, _ = torch.linalg.qr(matrix)
    if torch.det(q) < 0:
        q[:, 0] *= -1
    data.pos = data.pos @ q.T
    return data


