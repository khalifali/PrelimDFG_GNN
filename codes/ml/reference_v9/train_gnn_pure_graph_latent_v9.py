def string_list(array, fallback):
    if array is None:
        return list(fallback)
    return [str(value) for value in np.asarray(array).tolist()]


def normalized_feature_name(name):
    """Normalize feature labels so harmless naming differences still match."""
    return re.sub(r"[^a-z0-9]+", "", str(name).lower())


def select_named_features(values, names, requested, kind):
    """Return selected columns and their original labels."""
    lookup = {normalized_feature_name(name): index for index, name in enumerate(names)}
    indices = []
    selected_names = []
    missing = []
    for requested_name in requested:
        key = normalized_feature_name(requested_name)
        if key not in lookup:
            missing.append(requested_name)
        else:
            index = lookup[key]
            indices.append(index)
            selected_names.append(names[index])
    if missing:
        raise ValueError(
            f"Requested {kind} feature(s) not found: {missing}. "
            f"Available {kind} features: {names}"
        )
    return values[:, indices], selected_names


def minimal_feature_selection(node, node_names, edge, edge_names):
    """Keep only nonconstant structural scalars; coordinates are added later."""
    node, node_names = select_named_features(
        node,
        node_names,
        ["radial_distance_over_rg", "coordination"],
        "node",
    )
    edge, edge_names = select_named_features(
        edge,
        edge_names,
        ["distance_over_dref"],
        "edge",
    )
    return node, node_names, edge, edge_names


class Model(nn.Module):
    """Pure graph GNN whose targets are predicted only from the latent vector."""

    def __init__(self, nin, ein, nout, global_dim=0, hidden=64, latent=4,
                 layers=6, dropout=0.1):
        super().__init__()
        # Three normalized coordinates and three relative-vector components
        # are added dynamically to the stored node and edge features.
        self.node = nn.Linear(nin + 3, hidden)
        self.edge = nn.Linear(ein + 3, hidden)
        self.layers = nn.ModuleList([
            GINEConv(nn.Sequential(
                nn.Linear(hidden, hidden), nn.ReLU(), nn.Linear(hidden, hidden)
            ))
            for _ in range(layers)
        ])
        self.norms = nn.ModuleList([nn.LayerNorm(hidden) for _ in range(layers)])
        self.dropout = nn.Dropout(dropout)
        # The graph-derived representation is the model's only information
        # path. No precomputed aggregate descriptors are supplied to either
        # the latent bottleneck or the prediction head.
        self.to_latent = nn.Linear(3 * hidden, latent)
        self.head = nn.Sequential(
            nn.Linear(latent, 16), nn.ReLU(), nn.Linear(16, nout)
        )

    def forward(self, data):
        source, target = data.edge_index
        relative_vector = data.pos[target] - data.pos[source]
        x = self.node(torch.cat((data.x, data.pos), dim=1))
        edge = self.edge(torch.cat((data.edge_attr, relative_vector), dim=1))
        for layer, norm in zip(self.layers, self.norms):
            update = self.dropout(torch.relu(layer(x, data.edge_index, edge)))
            x = norm(x + update)
        count = global_add_pool(torch.ones_like(x[:, :1]), data.batch)
        graph_pooled = torch.cat((
            global_mean_pool(x, data.batch),
            global_max_pool(x, data.batch),
            global_add_pool(x, data.batch) / torch.sqrt(count.clamp_min(1.0)),
        ), dim=1)
        latent = self.to_latent(graph_pooled)
        return self.head(latent), latent


def graph_paths(root):
    # Current preprocessing layout: gnn_dataset/case_.../graph.npz
    paths = sorted(root.glob("case_*/graph.npz"))
    if not paths:
        # Useful fallback if graphs were placed one level deeper.
        paths = sorted(root.rglob("graph.npz"))
    return paths


def realization_group(case_name):
    """Remove the realization suffix while retaining the physical parameters."""
    match = re.search(
        r"(?:^|_)dp([^_]+)_N([^_]+)_Df([^_]+)", case_name, flags=re.IGNORECASE
    )
    if match:
        return "dp{}_N{}_Df{}".format(*match.groups()).lower()
    name = re.sub(r"_rep(?:licate)?_?\d+$", "", case_name, flags=re.IGNORECASE)
    return re.sub(r"^case_\d+_", "", name, flags=re.IGNORECASE)


def make_grouped_folds(data, number_of_folds, seed):
    groups = {}
    for index, graph in enumerate(data):
        groups.setdefault(realization_group(graph.case), []).append(index)
    if len(groups) < number_of_folds:
        raise ValueError(
            f"Only {len(groups)} independent parameter groups are available for "
            f"{number_of_folds} grouped folds"
        )
    rng = np.random.default_rng(seed)
    group_items = list(groups.values())
    rng.shuffle(group_items)
    group_items.sort(key=len, reverse=True)
    folds = [[] for _ in range(number_of_folds)]
    for indices in group_items:
        smallest = min(range(number_of_folds), key=lambda i: len(folds[i]))
        folds[smallest].extend(indices)
    return [np.asarray(fold, dtype=int) for fold in folds]


def load_dataset(root, contact_overlap_tolerance=1.0e-6,
                 include_non_touching=False, feature_set="minimal"):
    data = []
    reference = None
    skipped = []

    for path in graph_paths(root):
        try:
            with np.load(path, allow_pickle=False) as arrays:
                node = np.asarray(arrays["node_features"], dtype=np.float32)
                edge_index = np.asarray(arrays["edge_index"], dtype=np.int64)
                edge = np.asarray(arrays["edge_features"], dtype=np.float32)
                targets = np.asarray(arrays["targets"], dtype=np.float32).reshape(-1)
                if "positions" not in arrays:
                    raise ValueError(
                        "graph.npz has no 'positions' array; rerun preprocessing "
                        "with particle positions enabled"
                    )
                position = np.asarray(arrays["positions"], dtype=np.float32)
                node_names = string_list(
                    arrays["node_feature_names"] if "node_feature_names" in arrays else None,
                    [f"node_{i}" for i in range(node.shape[1])],
                )
                edge_names = string_list(
                    arrays["edge_feature_names"] if "edge_feature_names" in arrays else None,
                    [f"edge_{i}" for i in range(edge.shape[1])],
                )
                target_names = string_list(
                    arrays["target_names"] if "target_names" in arrays else None,
                    GRAPH_TARGET_FALLBACK,
                )

            if node.ndim != 2 or edge.ndim != 2 or edge_index.shape[0] != 2:
                raise ValueError(
                    f"invalid shapes: node={node.shape}, edge={edge.shape}, "
                    f"edge_index={edge_index.shape}"
                )
            if edge.shape[0] != edge_index.shape[1]:
                raise ValueError("edge_features rows do not match edge_index columns")
            if position.shape != (node.shape[0], 3):
                raise ValueError(f"invalid particle-position shape: {position.shape}")
            if len(target_names) != len(targets):
                raise ValueError("target_names and targets have different lengths")
            if EXPOSURE_TARGET not in target_names:
                raise ValueError(
                    f"required target {EXPOSURE_TARGET!r} is absent; "
                    f"available targets: {target_names}"
                )
            exposure_index = target_names.index(EXPOSURE_TARGET)
            targets = targets[[exposure_index]]
            target_names = [EXPOSURE_TARGET]
            if not all(np.isfinite(a).all() for a in (node, edge, position, targets)):
                raise ValueError("graph contains NaN or infinite values")

            # Centre positions and normalize them by the reference diameter.
            # If the first edge feature is distance/d_ref, d_ref follows from
            # the ratio of physical and normalized contact distances.
            centered = position - position.mean(axis=0, keepdims=True)
            if edge_index.shape[1] and edge.shape[1]:
                raw_distance = np.linalg.norm(
                    position[edge_index[1]] - position[edge_index[0]], axis=1
                )
                valid_scale = (edge[:, 0] > 1e-12) & (raw_distance > 1e-12)
                d_ref = float(np.median(raw_distance[valid_scale] / edge[valid_scale, 0])) \
                    if np.any(valid_scale) else 1.0
            else:
                d_ref = 1.0
            normalized_position = centered / max(d_ref, 1e-12)

            # Restrict message passing to geometrically touching (or
            # numerically near-touching) particle pairs.  The first stored node
            # feature is r_i/d_ref in the present graph format, so the
            # dimensionless geometrical overlap is obtained independently of
            # the adhesive interaction cut-off used by the DEM solver.
            if not include_non_touching and edge_index.shape[1]:
                normalized_radius = node[:, 0]
                normalized_distance = np.linalg.norm(
                    normalized_position[edge_index[1]]
                    - normalized_position[edge_index[0]], axis=1
                )
                normalized_overlap = (
                    normalized_radius[edge_index[0]]
                    + normalized_radius[edge_index[1]]
                    - normalized_distance
                )
                touching = normalized_overlap >= -contact_overlap_tolerance
                edge_index = edge_index[:, touching]
                edge = edge[touching]
                if edge_index.shape[1] == 0:
                    raise ValueError(
                        "contact-only filtering removed every graph edge"
                    )

            # Feature selection is intentionally performed after contact
            # filtering, because the stored radius is needed to decide which
            # reported adhesive pairs are geometrically touching.  Particle
            # coordinates and relative edge vectors are supplied separately
            # by the model and are retained for every feature set.
            stored_node_names = list(node_names)
            stored_edge_names = list(edge_names)
            if feature_set == "minimal":
                node, node_names, edge, edge_names = minimal_feature_selection(
                    node, node_names, edge, edge_names
                )

            signature = (node.shape[1], edge.shape[1], len(targets),
                         tuple(node_names), tuple(edge_names), tuple(target_names))
            if reference is None:
                reference = signature
            elif signature != reference:
                raise ValueError(
                    "feature layout differs from the first graph; rerun preprocessing "
                    "with consistent VTK fields"
                )

            graph = Data(
                x=torch.from_numpy(node),
                edge_index=torch.from_numpy(edge_index),
                edge_attr=torch.from_numpy(edge),
                pos=torch.from_numpy(normalized_position.astype(np.float32)),
                y=torch.from_numpy(targets).view(1, -1),
            )
            graph.case = path.parent.name
            data.append(graph)
        except Exception as exc:
            skipped.append({"path": str(path), "error": str(exc)})

    if reference is None:
        return data, None, skipped
    metadata = {
        "node_feature_count": reference[0],
        "edge_feature_count": reference[1],
        "target_count": reference[2],
        "node_feature_names": list(reference[3]),
        "edge_feature_names": list(reference[4]),
        "stored_node_feature_names": stored_node_names,
        "stored_edge_feature_names": stored_edge_names,
        "feature_set": feature_set,
        "target_names": list(reference[5]),
        "global_feature_names": [],
        "diagnostic_descriptor_names": [
            "log_particle_count",
            "log_radius_of_gyration_over_d_ref",
            "mean_coordination",
            "maximum_coordination",
        ],
        "latent_input": "graph_pooling_only",
        "global_feature_path": "not_used_by_model",
        "prediction_head_input": "latent_vector_only",
        "graph_pooling": "mean_max_and_size_normalized_add",
        "edge_selection": (
            "all_reported_pairs" if include_non_touching
            else "geometrically_touching_pairs"
        ),
        "contact_overlap_tolerance_over_d_ref": (
            None if include_non_touching else contact_overlap_tolerance
        ),
    }
    return data, metadata, skipped


def out_of_fold_metrics(predictions, target_names):
    """Calculate metrics from the combined test predictions of all folds."""
    truth = np.asarray([
        [row[f"true_{target}"] for target in target_names]
        for row in predictions
    ], dtype=float)
    predicted = np.asarray([
        [row[f"pred_{target}"] for target in target_names]
        for row in predictions
    ], dtype=float)

    residual = predicted - truth
    rmse = np.sqrt(np.mean(residual ** 2, axis=0))
    mae = np.mean(np.abs(residual), axis=0)
    ss_res = np.sum(residual ** 2, axis=0)
    ss_tot = np.sum((truth - np.mean(truth, axis=0)) ** 2, axis=0)
    r_squared = np.full_like(ss_tot, np.nan)
    valid = ss_tot > 0.0
    r_squared[valid] = 1.0 - ss_res[valid] / ss_tot[valid]

    return {
        target: {
            "rmse": float(rmse[index]),
            "mae": float(mae[index]),
            "r_squared": (
                float(r_squared[index]) if np.isfinite(r_squared[index]) else None
            ),
        }
        for index, target in enumerate(target_names)
    }


def plot_out_of_fold_predictions(predictions, target_names, metrics, output):
    """Create parity plots from the combined held-out predictions."""
    number = len(target_names)
    figure, axes = plt.subplots(1, number, figsize=(4.75 * number, 4.5))
    figure.subplots_adjust(
        left=0.065, right=0.925, bottom=0.15, top=0.94, wspace=0.16
    )
    axes = np.atleast_1d(axes)
    folds = np.asarray([row["fold"] for row in predictions], dtype=int)
    fold_ids = np.unique(folds)

    # The fold index is categorical.  Use exactly one colour bin per fold
    # instead of allowing Matplotlib to interpolate through all ten colours
    # of ``tab10`` between the minimum and maximum fold indices.
    base_colours = plt.get_cmap("tab10").colors
    fold_cmap = ListedColormap(
        [base_colours[index % len(base_colours)] for index in range(len(fold_ids))]
    )
    fold_boundaries = np.arange(len(fold_ids) + 1) - 0.5
    fold_norm = BoundaryNorm(fold_boundaries, fold_cmap.N)
    fold_to_colour_index = {
        fold_id: index for index, fold_id in enumerate(fold_ids)
    }
    fold_colours = np.asarray([fold_to_colour_index[value] for value in folds])

    for axis, target in zip(axes, target_names):
        truth = np.asarray([row[f"true_{target}"] for row in predictions])
        predicted = np.asarray([row[f"pred_{target}"] for row in predictions])
        lower = float(min(truth.min(), predicted.min()))
        upper = float(max(truth.max(), predicted.max()))
        margin = 0.05 * max(upper - lower, 1e-8)

        scatter = axis.scatter(
            truth, predicted, c=fold_colours, cmap=fold_cmap, norm=fold_norm, s=34,
            alpha=0.82, edgecolors="black", linewidths=0.3
        )
        axis.plot(
            [lower - margin, upper + margin],
            [lower - margin, upper + margin],
            color="black", linestyle="--", linewidth=1.1,
            label="Ideal prediction",
        )
        axis.set_xlim(lower - margin, upper + margin)
        axis.set_ylim(lower - margin, upper + margin)
        axis.set_aspect("equal", adjustable="box")
        axis.set_xlabel("Reference", fontsize=12)
        axis.set_ylabel("Out-of-fold prediction", fontsize=12)
        axis.set_title(
            TARGET_LABELS.get(target, target.replace("_", " ")), fontsize=13
        )
        axis.tick_params(labelsize=11)
        values = metrics[target]
        axis.text(
            0.04, 0.96,
            rf"$R^2={values['r_squared']:.3f}$" + "\n"
            + rf"$\mathrm{{RMSE}}={values['rmse']:.3f}$" + "\n"
            + rf"$\mathrm{{MAE}}={values['mae']:.3f}$",
            transform=axis.transAxes, va="top", ha="left", fontsize=10.5,
            bbox={"boxstyle": "round", "facecolor": "white", "alpha": 0.88},
        )
        axis.grid(alpha=0.2)

    colourbar = figure.colorbar(
        scatter, ax=axes.tolist(), ticks=np.arange(len(fold_ids)),
        boundaries=fold_boundaries, spacing="uniform", shrink=0.84, pad=0.02
    )
    colourbar.set_ticklabels([str(value + 1) for value in fold_ids])
    colourbar.ax.tick_params(labelsize=11)
    colourbar.set_label("Held-out test fold", fontsize=12)
    figure.savefig(output, dpi=300, bbox_inches="tight")
    plt.close(figure)


def plot_fold_rmse(fold_scores, target_names, output):
    """Show fold-to-fold RMSE variation using one scale per target."""
    scores = np.asarray(fold_scores, dtype=float)
    number = len(target_names)
    figure, axes = plt.subplots(
        1, number, figsize=(4.7 * number, 3.9), constrained_layout=True
    )
    axes = np.atleast_1d(axes)
    folds = np.arange(1, scores.shape[0] + 1)

    for index, (axis, target) in enumerate(zip(axes, target_names)):
        axis.bar(folds, scores[:, index], color="#3070B3", edgecolor="black")
        axis.axhline(
            scores[:, index].mean(), color="#D1495B", linestyle="--",
            linewidth=1.4, label="Fold mean",
        )
        axis.set_xticks(folds)
        axis.set_xlabel("Test fold")
        axis.set_ylabel("RMSE")
        axis.set_title(TARGET_LABELS.get(target, target.replace("_", " ")))
        axis.grid(axis="y", alpha=0.2)
        axis.legend(frameon=False)

    figure.suptitle("Variation of prediction error between test folds", fontsize=13)
    figure.savefig(output, dpi=300, bbox_inches="tight")
    plt.close(figure)


